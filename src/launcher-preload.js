'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');
const invoke = (name, ...args) => ipcRenderer.invoke(`launcher:${name}`, ...args);
contextBridge.exposeInMainWorld('launcher', {
  state: () => invoke('state'),
  close: () => invoke('close'),
  minimize: () => invoke('minimize'),
  settings: () => invoke('settings'),
  pinWindow: (pinned) => invoke('pin-window', pinned),
  petRest: (sleeping) => invoke('pet-rest', sleeping),
  onPetState: (fn) => ipcRenderer.on('launcher:pet-state', (_e, state) => fn(state)),
  confirmDrop: (id, choices) => invoke('drop-confirm', id, choices),
  cancelDrop: () => invoke('drop-cancel'),
  choose: () => invoke('choose'),
  importFiles: (files, category) => invoke('import', Array.from(files, (file) => webUtils.getPathForFile(file)), category),
  importPaths: (paths, category) => invoke('import', paths, category),
  addCategory: (name) => invoke('category-add', name),
  removeCategory: (id) => invoke('category-remove', id),
  move: (id, category) => invoke('move', id, category),
  reorder: (id, beforeId) => invoke('reorder', id, beforeId),
  folders: {
    choose: () => invoke('folder-choose'),
    importFiles: (files) => invoke('folder-import', Array.from(files, (file) => webUtils.getPathForFile(file))),
    importPaths: (paths) => invoke('folder-import', paths),
    reorder: (id, beforeId) => invoke('folder-reorder', id, beforeId),
    remove: (id) => invoke('folder-remove', id),
    open: (id) => invoke('folder-open', id),
  },
  restore: (id) => invoke('restore', id),
  launch: (id) => invoke('launch', id),
  skin: (id) => invoke('skin', id),
  musicLayout: (visible, bounds) => invoke('music-layout', visible, bounds),
  musicAction: (action) => invoke('music-action', action),
  onMusicState: (fn) => ipcRenderer.on('launcher:music-state', (_e, state) => fn(state)),
  onTab: (fn) => ipcRenderer.on('launcher:tab', (_e, tab) => fn(tab)),
  onRefresh: (fn) => ipcRenderer.on('launcher:refresh', () => fn()),
  vpn: {
    getStatus: () => invoke('vpn', 'status'),
    start: () => invoke('vpn', 'start'),
    stop: () => invoke('vpn', 'stop'),
    restart: () => invoke('vpn', 'restart'),
    importFile: () => invoke('vpn', 'import-file'),
    importSubscription: (name, url) => invoke('vpn', 'import-subscription', { name, url }),
    updateSubscription: (id) => invoke('vpn', 'update-subscription', { id }),
    selectProfile: (id) => invoke('vpn', 'select-profile', { id }),
    rollbackProfile: (id) => invoke('vpn', 'rollback-profile', { id }),
    removeProfile: (id) => invoke('vpn', 'remove-profile', { id }),
    updateSettings: (patch) => invoke('vpn', 'settings', patch),
    selectProxy: (group, name) => invoke('vpn', 'select-proxy', { group, name }),
    setFavorite: (name, favorite) => invoke('vpn', 'favorite', { name, favorite }),
    delay: (name) => invoke('vpn', 'delay', { name }),
    service: (operation) => invoke('vpn', 'service', { operation }),
    onState: (fn) => ipcRenderer.on('launcher:vpn-state', (_e, state) => fn(state)),
  },
});
